"""Generate the Stage 11 SystemVerilog LUT ROM from editable curve parameters."""

from __future__ import annotations

import argparse
from pathlib import Path

from lighting_curves import generate_luts, load_parameters


REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_PARAMETERS = Path(__file__).with_name("lighting_curve_parameters.json")
DEFAULT_OUTPUT = (
    REPO_ROOT
    / "fpga/project/stage11_720p60hz_adaptive_image_enhancement_test"
    / "source/rtl/correction/lighting_lut_rom.sv"
)


def render(parameters_path: Path) -> str:
    luts = generate_luts(load_parameters(parameters_path))
    lines = [
        "`timescale 1ns / 1ps",
        "",
        "// Generated by host/pose/generate_lighting_lut_rom.py. Do not edit by hand.",
        "// Re-run the generator after changing lighting_curve_parameters.json.",
        "module lighting_lut_rom (",
        "    input  wire [2:0] profile_id,",
        "    input  wire [7:0] red_in, green_in, blue_in,",
        "    output reg  [7:0] red_out, green_out, blue_out",
        ");",
    ]
    for profile_id, table in luts.items():
        # Indexed part-select [value*8 +: 8] maps input 0 to the least-significant byte.
        packed = "".join(f"{int(value):02x}" for value in table[::-1])
        lines.append(f"    localparam [2047:0] LUT_{profile_id} = 2048'h{packed};")
    lines.extend(
        [
            "",
            "    function automatic [7:0] lookup(input [2:0] id, input [7:0] value);",
            "        begin",
            "            case (id)",
        ]
    )
    for profile_id in luts:
        lines.append(
            f"                3'd{profile_id}: lookup = LUT_{profile_id}[value*8 +: 8];"
        )
    lines.extend(
        [
            "                default: lookup = LUT_0[value*8 +: 8];",
            "            endcase",
            "        end",
            "    endfunction",
            "",
            "    always @* begin",
            "        red_out = lookup(profile_id, red_in);",
            "        green_out = lookup(profile_id, green_in);",
            "        blue_out = lookup(profile_id, blue_in);",
            "    end",
            "endmodule",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--parameters", type=Path, default=DEFAULT_PARAMETERS)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(args.parameters), encoding="utf-8", newline="\n")
    print(f"generated {args.output}")


if __name__ == "__main__":
    main()
